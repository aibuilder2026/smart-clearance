def envelope(vo):
    a = np.abs(vo); hop = 480
    frames = a[: len(a) // hop * hop].reshape(-1, hop).max(axis=1)
    on = (frames > 0.02).astype(np.float32)
    env, g = np.zeros_like(on), 0.0
    up, down = 1 - np.exp(-1 / (0.08 * SR / hop)), 1 - np.exp(-1 / (0.75 * SR / hop))
    for i, v in enumerate(on):
        g += (v - g) * (up if v > g else down); env[i] = g
    e = np.repeat(env, hop); e = np.pad(e, (0, N - len(e)), mode="edge")[:N]
    # it looks ahead: the music is already down as a line starts, so its first words ('not every batch') are clear
    la = int(0.3 * SR)
    return np.maximum(e, np.concatenate([e[la:], np.full(la, e[-1], np.float32)]))

def xfade_loop(x, length, fade):
    """x looped on itself to `length` samples, each join an equal-power crossfade of `fade` samples."""
    out = x.copy()
    w = np.linspace(0, 1, fade, dtype=np.float32)[:, None]
    fin, fout = np.sin(w * np.pi / 2), np.cos(w * np.pi / 2)
    while len(out) < length:
        out = np.concatenate([out[:-fade], out[-fade:] * fout + x[:fade] * fin, x[fade:]])
    return out[:length]

def music(env):
    bed = decode(MUS / "music-bed-6.mp3"); lift = decode(MUS / "music-lift-2.mp3")
    track = xfade_loop(bed, N, 3 * SR)
    close = int((P_.T[P_.LINES[-1]["id"]][0] - 3.0) * SR)  # the lift, from just before the close
    L2 = xfade_loop(lift, N - close, 3 * SR); F = 3 * SR
    w = np.linspace(0, 1, F, dtype=np.float32)[:, None]
    seg = track[close:].copy()
    seg[:F] = seg[:F] * np.cos(w * np.pi / 2) + L2[:F] * np.sin(w * np.pi / 2); seg[F:] = L2[F:]
    track[close:] = seg
    rms = np.sqrt(np.mean(track ** 2)); track *= db(-22) / max(rms, 1e-6)
    gain = (1 - 0.75 * env)[:, None]  # about -12 dB under the voice (cut 5: the voice about 12 dB over the bed)
    head = np.linspace(0, 1, int(1.5 * SR))[:, None]; track[: len(head)] *= head
    t_end = int((END - 3.5) * SR); tail = np.linspace(1, 0, N - t_end)[:, None]; track[t_end:] *= tail
    # room for the voice's consonants: the bed's presence band (1.2 to 5 kHz) goes further down under the voice, about
    # 20 dB, the rest about 12 ('batch' was heard as 'badge' over the piano)
    from scipy.signal import butter, sosfiltfilt
    band = sosfiltfilt(butter(2, [1200, 5000], btype="bandpass", fs=SR, output="sos"), track, axis=0).astype(np.float32)
    return (track - band) * gain + band * (1 - 0.9 * env)[:, None]

PINK_B, PINK_A = [0.049922035, -0.095993537, 0.050612699, -0.004408786], [1, -2.494956002, 2.017265875, -0.522189400]

def _sweep(x, cut):
    """a one-pole low-pass whose coefficient follows `cut` sample by sample: noise that opens and closes"""
    y = np.zeros_like(x); z = 0.0
    for i in range(len(x)):
        z += cut[i] * (x[i] - z); y[i] = z
    return y

def whoosh(rnd, d=1.6, peak=0.55, level=-23, lo=0.02, hi=0.25):
    n = int(d * SR); pink = lfilter(PINK_B, PINK_A, rnd.standard_normal(n).astype(np.float32))
    k = np.linspace(0, 1, n)
    env = np.where(k < peak, (k / peak) ** 2, ((1 - k) / (1 - peak)) ** 1.6)
    y = _sweep(pink, lo + hi * np.sin(np.pi * k))
    return (y / (np.abs(y).max() + 1e-6) * env * db(level)).astype(np.float32)

def riser(rnd, d=1.4, level=-27):
    """noise that brightens and swells into a moment, cut off just before it"""
    n = int(d * SR); pink = lfilter(PINK_B, PINK_A, rnd.standard_normal(n).astype(np.float32))
    k = np.linspace(0, 1, n)
    y = _sweep(pink, 0.01 + 0.35 * k ** 2)
    env = k ** 2.2 * (1 - np.clip((k - 0.97) / 0.03, 0, 1))
    return (y / (np.abs(y).max() + 1e-6) * env * db(level)).astype(np.float32)

def boom(d=1.8, level=-17, f0=62.0, f1=38.0):
    """a low hit: a sine whose pitch falls, with a soft attack and a long fall, and a short thump of filtered noise"""
    n = int(d * SR); t = np.arange(n) / SR
    f = f1 + (f0 - f1) * np.exp(-t / 0.18)
    ph = 2 * np.pi * np.cumsum(f) / SR
    env = (1 - np.exp(-t / 0.006)) * np.exp(-t / 0.55)
    y = np.sin(ph) * env
    rnd = np.random.default_rng(7); th = _sweep(rnd.standard_normal(n).astype(np.float32), np.full(n, 0.03)) * np.exp(-t / 0.05)
    y = y + 0.6 * th / (np.abs(th).max() + 1e-6)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def shutter(level=-21):
    """a camera's shutter: two short clicks of bright noise, 70 ms apart"""
    rnd = np.random.default_rng(11); n = int(0.16 * SR); y = np.zeros(n, np.float32)
    for at, ln, g in [(0.0, 0.009, 1.0), (0.07, 0.014, 0.75)]:
        i = int(at * SR); m = int(ln * SR)
        c = rnd.standard_normal(m).astype(np.float32)
        c = c - _sweep(c, np.full(m, 0.25))   # the high part only
        y[i:i + m] += c * np.exp(-np.arange(m) / (0.3 * m)) * g
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def chime(level=-25, notes=((1046.5, 0.0), (1568.0, 0.11))):
    """a payment's confirmation: two soft bell notes"""
    n = int(1.2 * SR); t = np.arange(n) / SR; y = np.zeros(n, np.float32)
    for f, at in notes:
        tt = np.clip(t - at, 0, None); on = (t >= at)
        y += on * (np.sin(2 * np.pi * f * tt) + 0.25 * np.sin(2 * np.pi * 2.01 * f * tt)) * (1 - np.exp(-tt / 0.004)) * np.exp(-tt / 0.32)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def tick(level=-31, f=880.0):
    """a soft tick as something lands: a short pitched tap with a little click"""
    n = int(0.12 * SR); t = np.arange(n) / SR
    y = np.sin(2 * np.pi * f * t) * np.exp(-t / 0.028) + 0.5 * np.sin(2 * np.pi * 2.02 * f * t) * np.exp(-t / 0.012)
    y *= 1 - np.exp(-t / 0.0015)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def glint(level=-29):
    """a bright shimmer for a word lighting up: three high partials, quickly fading"""
    n = int(0.9 * SR); t = np.arange(n) / SR
    y = sum(np.sin(2 * np.pi * f * t) * a for f, a in [(2093, 1.0), (3136, 0.6), (4186, 0.35)])
    y *= (1 - np.exp(-t / 0.01)) * np.exp(-t / 0.22)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def printer(d=0.32, level=-31):
    """a thermal label printer feeding a row: a stepper's buzz (noise chopped at its step rate) over a faint whine"""
    rnd = np.random.default_rng(31); n = int(d * SR); t = np.arange(n) / SR
    steps = (np.sin(2 * np.pi * 96 * t) > 0).astype(np.float32) * 0.8 + 0.2
    noise = rnd.standard_normal(n).astype(np.float32)
    hi = noise - _sweep(noise, np.full(n, 0.18))
    whine = 0.25 * np.sin(2 * np.pi * 1240 * t) * (1 + 0.3 * np.sin(2 * np.pi * 96 * t))
    env = np.clip(t / 0.02, 0, 1) * np.clip((d - t) / 0.04, 0, 1)
    y = (hi * steps * 0.7 + whine) * env
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def thud(level=-17):
    """a rubber stamp coming down: a short low hit and the slap of its face on paper"""
    lo = boom(0.55, level, 120.0, 70.0)
    rnd = np.random.default_rng(33); n = int(0.05 * SR)
    sl = rnd.standard_normal(n).astype(np.float32); sl = sl - _sweep(sl, np.full(n, 0.08))
    sl *= np.exp(-np.arange(n) / (0.012 * SR))
    lo[:n] += sl / (np.abs(sl).max() + 1e-6) * db(level - 4)
    return lo

def click(level=-30):
    """a pointer's click: a tiny bright tap"""
    rnd = np.random.default_rng(35); n = int(0.03 * SR)
    c = rnd.standard_normal(n).astype(np.float32); c = c - _sweep(c, np.full(n, 0.3))
    c *= np.exp(-np.arange(n) / (0.004 * SR))
    return (c / (np.abs(c).max() + 1e-6) * db(level)).astype(np.float32)

def notif(level=-26):
    """a notification landing: two quick bright notes"""
    return chime(level, notes=((1318.5, 0.0), (1975.5, 0.075)))

def sparkle(d=0.7, n=14, level=-36, seed=37):
    """a burst of tiny ticks at scattered pitches: many small things arriving at once"""
    rnd = np.random.default_rng(seed); out = np.zeros(int((d + 0.15) * SR), np.float32)
    for k in range(n):
        at = rnd.uniform(0, d) ** 1.4 / d ** 0.4
        y = tick(level + rnd.uniform(-4, 2), rnd.uniform(1300, 2600))
        i = int(at * SR); out[i:i + len(y)] += y[:len(out) - i]
    return out

class Air(np.ndarray):
    """a sound made of air (a whoosh, a riser, a sparkle of ticks): its noise sits where the voice's consonants do, so it
    is ducked further under the voice than the hits are"""


