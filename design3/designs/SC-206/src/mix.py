"""SC-206 (cut 3): the film's sound, laid on the voice's own clock (parts.T), then muxed under the silent cut.

- the voice-over: each line of the chosen Indian English take (Maya1, tts/vo3/<voice>, named in tts/voice.txt) at its
  start, upsampled to 48 kHz, then one voice chain in ffmpeg (a high-pass, a little warmth and presence, gentle
  compression, a faint short room so it is not bone-dry);
- the music: SC-187's felt-piano bed (Lyria 2, already in design3/designs/SC-187/media, reused: no new generation)
  looped on itself through equal-power crossfades, its dominant-key lift crossfaded in for the close, ducked under
  the voice by its own envelope, faded out on the end card;
- sound design, all synthesised here from noise and sine tones (nothing sampled, nothing generated by a model): soft
  whooshes under the chapter changes and each whip pan, an airy swell as a device comes into focus, a riser and a low
  hit as the mark lands and as each result lands, a camera shutter at the landfill, a two-note chime as the UPI
  payment goes through;
- one loudness pass (two-pass loudnorm to -14 LUFS, true peak -1.5 dB), then the mux, and an .srt of the narration.

  .venv/bin/python mix.py [--preview]
"""
import json, re, subprocess, sys
from pathlib import Path
import numpy as np, soundfile as sf
from scipy.signal import resample_poly, lfilter

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import parts as P_
B = HERE / "build"
VO = P_.TAKE
MUS = Path("/Users/arundutta/projects/smart-clearance/design3/designs/SC-187/media")
SR = 48000
END = P_.END
LINES = {l["id"]: l for l in P_.LINES}
N = int((END + 0.5) * SR)

def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: sys.stderr.write(r.stderr[-3000:]); raise SystemExit("ffmpeg failed")
    return r

def decode(path):
    tmp = B / f"_dec-{path.stem}.wav"
    run(["ffmpeg", "-v", "error", "-y", "-i", str(path), "-ar", str(SR), "-ac", "2", "-c:a", "pcm_f32le", str(tmp)])
    x, _ = sf.read(tmp, dtype="float32"); return x

def db(v): return 10 ** (v / 20)

def voice():
    vo = np.zeros(N, dtype=np.float32)
    for lid, (t0, t1) in P_.T.items():
        x, sr = sf.read(VO / f"{lid}.wav", dtype="float32")
        for cut, add in sorted(P_.PAUSE.get(lid, []), key=lambda c: -(c[0] or 0)):   # parts.PAUSE: silence inside the line
            i = int((cut if cut is not None else len(x) / sr) * sr)
            x = np.concatenate([x[:i], np.zeros(int(add * sr), np.float32), x[i:]])
        x = resample_poly(x, SR // 8000, sr // 8000).astype(np.float32)
        i = int(t0 * SR); vo[i:i + len(x)] += x[: N - i]
    raw = B / "vo-raw.wav"; sf.write(raw, vo, SR, subtype="FLOAT")
    fx = B / "vo-fx.wav"
    chain = ("highpass=f=75,equalizer=f=190:t=q:w=1.0:g=1.6,equalizer=f=3300:t=q:w=1.3:g=1.8,"
             "equalizer=f=7600:t=q:w=1.6:g=-1.6,acompressor=threshold=-21dB:ratio=2.4:attack=6:release=140:makeup=2.2,"
             "aecho=0.88:0.6:23|41:0.07|0.045,pan=stereo|c0=c0|c1=c0")
    run(["ffmpeg", "-v", "error", "-y", "-i", str(raw), "-af", chain, "-c:a", "pcm_f32le", str(fx)])
    y, _ = sf.read(fx, dtype="float32")
    return vo, y[:N]

def envelope(vo):
    a = np.abs(vo); hop = 480
    frames = a[: len(a) // hop * hop].reshape(-1, hop).max(axis=1)
    on = (frames > 0.02).astype(np.float32)
    env, g = np.zeros_like(on), 0.0
    up, down = 1 - np.exp(-1 / (0.08 * SR / hop)), 1 - np.exp(-1 / (0.75 * SR / hop))
    for i, v in enumerate(on):
        g += (v - g) * (up if v > g else down); env[i] = g
    e = np.repeat(env, hop); return np.pad(e, (0, N - len(e)), mode="edge")[:N]

def xfade_loop(x, length, fade):
    """x looped on itself to `length` samples, each join an equal-power crossfade of `fade` samples."""
    out = x.copy()
    w = np.linspace(0, 1, fade, dtype=np.float32)[:, None]
    fin, fout = np.sin(w * np.pi / 2), np.cos(w * np.pi / 2)
    while len(out) < length:
        out = np.concatenate([out[:-fade], out[-fade:] * fout + x[:fade] * fin, x[fade:]])
    return out[:length]

def music(env):
    bed = decode(MUS / "music-bed-6.mp3"); lift = decode(MUS / "music-lift-2.mp3")
    track = xfade_loop(bed, N, 3 * SR)
    close = int((P_.T["e01"][0] - 3.0) * SR)  # the lift, from just before the close
    L2 = xfade_loop(lift, N - close, 3 * SR); F = 3 * SR
    w = np.linspace(0, 1, F, dtype=np.float32)[:, None]
    seg = track[close:].copy()
    seg[:F] = seg[:F] * np.cos(w * np.pi / 2) + L2[:F] * np.sin(w * np.pi / 2); seg[F:] = L2[F:]
    track[close:] = seg
    rms = np.sqrt(np.mean(track ** 2)); track *= db(-22) / max(rms, 1e-6)
    gain = (1 - 0.66 * env)[:, None]  # about -9 dB under the voice
    head = np.linspace(0, 1, int(1.5 * SR))[:, None]; track[: len(head)] *= head
    t_end = int((END - 3.5) * SR); tail = np.linspace(1, 0, N - t_end)[:, None]; track[t_end:] *= tail
    return track * gain

PINK_B, PINK_A = [0.049922035, -0.095993537, 0.050612699, -0.004408786], [1, -2.494956002, 2.017265875, -0.522189400]

def _sweep(x, cut):
    """a one-pole low-pass whose coefficient follows `cut` sample by sample: noise that opens and closes"""
    y = np.zeros_like(x); z = 0.0
    for i in range(len(x)):
        z += cut[i] * (x[i] - z); y[i] = z
    return y

def whoosh(rnd, d=1.6, peak=0.55, level=-23, lo=0.02, hi=0.25):
    n = int(d * SR); pink = lfilter(PINK_B, PINK_A, rnd.standard_normal(n).astype(np.float32))
    k = np.linspace(0, 1, n)
    env = np.where(k < peak, (k / peak) ** 2, ((1 - k) / (1 - peak)) ** 1.6)
    y = _sweep(pink, lo + hi * np.sin(np.pi * k))
    return (y / (np.abs(y).max() + 1e-6) * env * db(level)).astype(np.float32)

def riser(rnd, d=1.4, level=-27):
    """noise that brightens and swells into a moment, cut off just before it"""
    n = int(d * SR); pink = lfilter(PINK_B, PINK_A, rnd.standard_normal(n).astype(np.float32))
    k = np.linspace(0, 1, n)
    y = _sweep(pink, 0.01 + 0.35 * k ** 2)
    env = k ** 2.2 * (1 - np.clip((k - 0.97) / 0.03, 0, 1))
    return (y / (np.abs(y).max() + 1e-6) * env * db(level)).astype(np.float32)

def boom(d=1.8, level=-17, f0=62.0, f1=38.0):
    """a low hit: a sine whose pitch falls, with a soft attack and a long fall, and a short thump of filtered noise"""
    n = int(d * SR); t = np.arange(n) / SR
    f = f1 + (f0 - f1) * np.exp(-t / 0.18)
    ph = 2 * np.pi * np.cumsum(f) / SR
    env = (1 - np.exp(-t / 0.006)) * np.exp(-t / 0.55)
    y = np.sin(ph) * env
    rnd = np.random.default_rng(7); th = _sweep(rnd.standard_normal(n).astype(np.float32), np.full(n, 0.03)) * np.exp(-t / 0.05)
    y = y + 0.6 * th / (np.abs(th).max() + 1e-6)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def shutter(level=-21):
    """a camera's shutter: two short clicks of bright noise, 70 ms apart"""
    rnd = np.random.default_rng(11); n = int(0.16 * SR); y = np.zeros(n, np.float32)
    for at, ln, g in [(0.0, 0.009, 1.0), (0.07, 0.014, 0.75)]:
        i = int(at * SR); m = int(ln * SR)
        c = rnd.standard_normal(m).astype(np.float32)
        c = c - _sweep(c, np.full(m, 0.25))   # the high part only
        y[i:i + m] += c * np.exp(-np.arange(m) / (0.3 * m)) * g
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def chime(level=-25, notes=((1046.5, 0.0), (1568.0, 0.11))):
    """a payment's confirmation: two soft bell notes"""
    n = int(1.2 * SR); t = np.arange(n) / SR; y = np.zeros(n, np.float32)
    for f, at in notes:
        tt = np.clip(t - at, 0, None); on = (t >= at)
        y += on * (np.sin(2 * np.pi * f * tt) + 0.25 * np.sin(2 * np.pi * 2.01 * f * tt)) * (1 - np.exp(-tt / 0.004)) * np.exp(-tt / 0.32)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def glint(level=-29):
    """a bright shimmer for a word lighting up: three high partials, quickly fading"""
    n = int(0.9 * SR); t = np.arange(n) / SR
    y = sum(np.sin(2 * np.pi * f * t) * a for f, a in [(2093, 1.0), (3136, 0.6), (4186, 0.35)])
    y *= (1 - np.exp(-t / 0.01)) * np.exp(-t / 0.22)
    return (y / (np.abs(y).max() + 1e-6) * db(level)).astype(np.float32)

def sfx():
    """the sound design, placed from the cut's own shots (shots3), so a re-timed cut keeps its sounds on their marks"""
    out = np.zeros((N, 2), dtype=np.float32); rnd = np.random.default_rng(206)
    import shots3 as S_, parts3 as P3_
    shots = S_.build(); sh = {s.name: s for s in shots}

    def lay(y, t, pan=0.5, anchor=0.0):
        """y laid with its own `anchor` (seconds into it) at film time t; pan 0 left, 1 right"""
        i0 = int((t - anchor) * SR)
        if i0 < 0: y = y[-i0:]; i0 = 0
        seg = y[: max(0, N - i0)]
        out[i0:i0 + len(seg), 0] += seg * np.sqrt(1 - pan) * 1.41; out[i0:i0 + len(seg), 1] += seg * np.sqrt(pan) * 1.41

    for name, lead in [("agents", 1.6), ("agenda", 0.3), ("signins", 0.25), ("chips", 0.25)]:
        if name in sh: lay(whoosh(rnd), sh[name].t0 + lead, anchor=0.9)
    b = sh["brand"]; bs = b.bg
    lay(riser(rnd, 1.5), b.t0 + 0.6, anchor=1.5)          # into the mark
    lay(boom(level=-18), b.t0 + 0.6)                      # the mark lands
    lay(whoosh(rnd, 0.7, 0.4, -27, 0.05, 0.35), b.t0 + bs.t_strike, pan=0.35, anchor=0.25)   # 'write-offs' struck out
    lay(glint(), b.t0 + bs.t_recovery + 0.1, pan=0.62)   # 'recovery' lights
    lay(whoosh(rnd, 1.3, 0.5, -25), b.t0 + bs.t_fly, anchor=0.6)   # the page comes into focus
    for s in shots:
        g = s.bg
        if isinstance(g, P3_.DeviceShot):
            if g.face is not None:   # the whip pan from the face to over the shoulder
                lay(whoosh(rnd, 0.55, 0.45, -24, 0.04, 0.45), s.t0 + g.t_whip + 0.2, pan=0.5 + 0.3 * g.whip_dir, anchor=0.25)
            lay(whoosh(rnd, g.go_len + 0.5, 0.7, -29, 0.01, 0.12), s.t0 + g.t_go, anchor=0.15)   # the device into focus
        if isinstance(g, P3_.ResultPunch):
            lay(riser(rnd, 1.2, -29), s.t0 + g.u0 + 0.3, anchor=1.2)
            lay(boom(level=-19, f0=70, f1=44), s.t0 + g.u0 + 0.35)
            for k, fa in enumerate(g.fact_at):
                lay(glint(-33), s.t0 + fa, pan=0.3 + 0.2 * k)
        if isinstance(g, P3_.UpiScene):
            lay(chime(), s.t0 + g.t_paid, pan=0.68)
        if type(g).__name__ == "CamView":
            lay(shutter(), s.t0 + g.u_shot, pan=0.42)
    if "end" in sh: lay(boom(2.4, -20, 55, 34), sh["end"].t0 + 0.4)
    return out

def srt():
    def ts(x):
        h, m = int(x // 3600), int(x % 3600 // 60); s = x % 60
        return f"{h:02d}:{m:02d}:{int(s):02d},{int(round((s - int(s)) * 1000)):03d}"
    rows = []
    for k, (lid, (t0, t1)) in enumerate(P_.T.items(), 1):
        text = LINES[lid]["text"].replace("Expire Soon", "ExpireSoon")
        rows.append(f"{k}\n{ts(t0)} --> {ts(t1 + 0.25)}\n{text}\n")
    (B / "smart-clearance-working-demo.srt").write_text("\n".join(rows))

def main():
    preview = "--preview" in sys.argv
    vo_raw, vo = voice(); env = envelope(vo_raw)
    mix = vo + music(env) + sfx()
    pre = B / "mix-pre.wav"; sf.write(pre, mix.astype(np.float32), SR, subtype="FLOAT")
    r = run(["ffmpeg", "-hide_banner", "-y", "-i", str(pre), "-af", "loudnorm=I=-14:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"])
    m = json.loads(re.findall(r"\{[^{}]*\}", r.stderr)[-1])
    ln = (f"loudnorm=I=-14:TP=-1.5:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:measured_LRA={m['input_lra']}:"
          f"measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
    final = B / "mix.wav"
    run(["ffmpeg", "-v", "error", "-y", "-i", str(pre), "-af", ln, "-ar", str(SR), "-c:a", "pcm_s24le", str(final)])
    silent = B / ("film-preview.mp4" if preview else "film-silent.mp4")
    out = B / ("film-preview-av.mp4" if preview else "smart-clearance-working-demo.mp4")
    run(["ffmpeg", "-v", "error", "-y", "-i", str(silent), "-i", str(final), "-map", "0:v", "-map", "1:a", "-c:v", "copy",
         "-c:a", "aac", "-b:a", "256k", "-shortest", "-movflags", "+faststart", str(out)])
    srt(); print("mixed", out, f"(input {m['input_i']} LUFS)")

if __name__ == "__main__":
    main()
